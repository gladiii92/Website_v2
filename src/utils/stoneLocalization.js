export function getLocalizedStoneName(stone, lang = 'de') {
  if (!stone) return '';
  const langKey = ['de', 'en', 'fr'].includes(lang) ? lang : 'de';
  return stoneNamesByLang[langKey]?.[stone.id] || stone[`name_${langKey}`] || stone.name;
}

